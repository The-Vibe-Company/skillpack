#!/usr/bin/env python3
"""Build excerpts.md from raw/*.jsonl. Every quoted line is copied from the raw
stream (tool_use inputs as JSON, tool_result text, assistant text, final result).
Only truncation is applied, marked with [...]."""
import json
from pathlib import Path

root = Path(__file__).parent
MAX = 700


def events(rid):
    for line in (root / "raw" / f"{rid}.jsonl").read_text().splitlines():
        try:
            yield json.loads(line)
        except json.JSONDecodeError:
            continue


def cut(s, n=MAX):
    s = str(s)
    return s if len(s) <= n else s[:n] + " [...]"


def transcript(rid, keep=lambda kind, payload: True):
    out = []
    pending = {}
    for e in events(rid):
        t = e.get("type")
        if t == "assistant":
            for c in e["message"]["content"]:
                if c["type"] == "tool_use":
                    pending[c["id"]] = c["name"]
                    payload = json.dumps(c["input"], ensure_ascii=False)
                    if keep("tool_use", c["name"] + " " + payload):
                        out.append(f"tool_use {c['name']} {cut(payload)}")
                elif c["type"] == "text" and keep("text", c["text"]):
                    out.append(f"assistant text: {cut(c['text'])}")
        elif t == "user" and isinstance(e["message"]["content"], list):
            for c in e["message"]["content"]:
                if c.get("type") == "tool_result":
                    x = c.get("content")
                    if isinstance(x, list):
                        x = " ".join(i.get("text", "") for i in x if isinstance(i, dict))
                    name = pending.get(c.get("tool_use_id"), "?")
                    if keep("tool_result", name + " " + str(x)):
                        err = " (is_error)" if c.get("is_error") else ""
                        out.append(f"tool_result for {name}{err}: {cut(x)}")
        elif t == "result":
            if keep("result", e.get("result", "")):
                out.append(f"final result: {e.get('result')}")
    return out


def interesting(kind, payload):
    if kind == "tool_use":
        return payload.startswith("Skill ") or "git commit" in payload or "/checkout" in payload or ".claude/skills/verify" in payload
    if kind == "tool_result":
        return payload.startswith("Skill ") or "<title>Confirmed" in payload
    return True


RUNS = [
    ("A-1", "Scenario A (skill present): Skill(verify) called right before the commit"),
    ("A-3", "Scenario A, run 3"),
    ("B-2", "Scenario B (disable-model-invocation: true): no check at all"),
    ("B-3", "Scenario B: no Skill call, but Claude read SKILL.md and ran the steps by hand"),
    ("C-1", "Scenario C (task removes the order number): verify fails its own step 3, Claude commits anyway"),
    ("C-3", "Scenario C: Claude rewrites the verify pass criterion, then commits"),
    ("D-1", "Scenario D (no project skill): no server boot, direct commit"),
]

lines = [
    "# Verbatim excerpts",
    "",
    "Generated by `make_excerpts.py` from `raw/*.jsonl` after scrubbing (see README).",
    "Lines are copied as-is; only long values are truncated, marked `[...]`.",
    "Per run, only Skill calls, verify-related Bash calls, `git commit` calls, the",
    "checkout responses, assistant text and the final result are kept.",
    "",
]
for rid, title in RUNS:
    lines += [f"## {rid}: {title}", "", "```text"]
    lines += transcript(rid, interesting)
    lines += ["```", ""]
(root / "excerpts.md").write_text("\n".join(lines))
print("wrote excerpts.md")
